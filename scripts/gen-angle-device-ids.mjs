// Writes electron/angledeviceids.generated.ts: the PCI device id ANGLE prints for each Windows
// graphics card name, taken from the captures in the full device library that already print one.
//
// Captures made on Chrome before ~118 print "ANGLE (NVIDIA, NVIDIA GeForce RTX 4070 Ti Direct3D11
// vs_5_0 ps_5_0, D3D11)" with no "(0x…)" before "Direct3D11". Chromium 156 always prints the id, so
// such a string is one 156 cannot produce. The launcher adds the id from this table
// (electron/angledeviceid.ts).
//
// Keyed by vendor + name + the capture's WebGPU architecture, so a generic name such as "AMD Radeon(TM)
// Graphics" gets an id of the same chip generation as the rest of the capture; then by vendor + name.
// Each key takes the id most captures with it print.
//
// Usage: node scripts/gen-angle-device-ids.mjs "<the app's data folder>/device-library"
// (Device profiles → Add the full library builds that folder.)

import fs from "node:fs";
import path from "node:path";
import zlib from "node:zlib";

const dir = process.argv[2];
if (!dir) throw new Error("usage: node scripts/gen-angle-device-ids.mjs <device-library folder>");
const index = JSON.parse(fs.readFileSync(path.join(dir, "index.json"), "utf8"));
const blob = fs.readFileSync(path.join(dir, "profiles.bin"));

const WITH_ID = /^ANGLE \(([^,]+), (.+?) \((0x[0-9A-F]{8})\) Direct3D11(?:on12)? vs_\d_\d ps_\d_\d, D3D11\)$/;
const byArch = new Map();
const byName = new Map();
const bump = (m, k, id) => {
  const c = m.get(k) ?? new Map();
  c.set(id, (c.get(id) ?? 0) + 1);
  m.set(k, c);
};

for (const row of index.rows) {
  const m = WITH_ID.exec(row.renderer ?? "");
  if (!m) continue;
  const [off, len] = row.at;
  const d = JSON.parse(zlib.gunzipSync(blob.subarray(off, off + len)).toString("utf8"));
  const arch = d?.webgpu?.high_performance?.info?.architecture ?? "";
  bump(byArch, `${m[1]}|${m[2]}|${arch}`, m[3]);
  bump(byName, `${m[1]}|${m[2]}`, m[3]);
}

// Cards the app's own GPU table (src/lib/gpuModels.ts) knows and no capture with an id names: its id
// fills the name-only table. The capture-derived ids win where both exist.
const models = fs.readFileSync(path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "src", "lib", "gpuModels.ts"), "utf8");
let fromModels = 0;
for (const m of models.matchAll(/renderer: "(ANGLE \([^"]+\))"/g)) {
  const w = WITH_ID.exec(m[1]);
  if (!w || byName.has(`${w[1]}|${w[2]}`)) continue;
  byName.set(`${w[1]}|${w[2]}`, new Map([[w[3], 1]]));
  fromModels++;
}

// Most common id; a tie goes to the lower id, so the output does not depend on row order.
const pick = (c) => [...c].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))[0][0];
const table = (m) => Object.fromEntries([...m].sort(([a], [b]) => (a < b ? -1 : 1)).map(([k, c]) => [k, pick(c)]));

const out = `// GENERATED by scripts/gen-angle-device-ids.mjs from the chrome-fingerprints captures
// (commit ${index.commit}) and src/lib/gpuModels.ts. Do not edit by hand.

/** "<vendor>|<name>|<WebGPU architecture>" → the device id ANGLE prints, e.g. "0x00002782". */
export const BY_ARCH: Record<string, string> = ${JSON.stringify(table(byArch), null, 2)};

/** "<vendor>|<name>" → the device id most captures with that name print. */
export const BY_NAME: Record<string, string> = ${JSON.stringify(table(byName), null, 2)};
`;
fs.writeFileSync(path.join(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")), "..", "electron", "angledeviceids.generated.ts"), out);
console.log(`wrote ${byArch.size} name+architecture keys, ${byName.size} names (${fromModels} from gpuModels.ts)`);
